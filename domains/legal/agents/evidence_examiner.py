    async def aexamine(self, text: str) -> Tuple[str, Dict[str, Any]]:
        """执行证据法定三性审查与质证报告生成"""
        user_prompt = f"请对以下涉案案情材料与证据进行法定'三性'与举证质证推演审查：\n\n{text}"
        try:
            content, usage = await ainvoke_legal_text(
                system_prompt=_EVIDENCE_SYSTEM_PROMPT,
                user_prompt=user_prompt,
                timeout=10.0,
            )
            if content and "证据" in content:
                return content, usage
        except Exception as e:
            logger.warning(f"EvidenceExaminer LLM 异常: {e}，启用确定性质证规则引擎")

        fallback_report = self.examine_fallback(text)
        return fallback_report, {"prompt": 0, "completion": 0, "cost": 0.0}


