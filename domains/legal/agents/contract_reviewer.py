"""
domains/legal/agents/contract_reviewer.py
=========================================
合同智能审查与风险红线排查引擎（LLM 逐条审查 + 确定性法律红线门禁兜底）。
覆盖：违约责任不对等、超额高利违约金、管辖权陷阱、付款交付漏洞、霸王免责条款。
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Tuple
from domains.legal.agents.llm_client import ainvoke_legal_text


_CONTRACT_REVIEW_SYSTEM_PROMPT = """你是一名中国顶尖律所资深非诉合规与合同审查专家。请对用户提交的合同文本进行全面、逐条、严谨的法律风险审查与排雷。
要求：
1. 第一行以 `## 🔍 【合同智能审查与红线排查报告】` 开头。
2. 合同概况与基本要素健全度：主体、标的、履行期限、价款支付机制是否闭环。
3. 高危风险条款排查与红线修改建议（逐条列出）：
   - 【原条款摘录】：指出具体风险点（如违约责任不平等、违约金畸高超4倍LPR、管辖权偏袒对方、单方解除权无对等救济等）。
   - 【风险定级】：🚨 高危 / ⚠️ 中危 / 💡 优化建议。
   - 【修订红线方案（Redline）】：给出可直接替换的原条款规范合规修订文本。
4. 综合签约防坑建议与履约留痕指引。"""


class ContractReviewer:
    """合同智能审查与红线标注引擎"""

    def review_fallback(self, contract_text: str) -> str:
        lines = [
            "## 🔍 【合同智能审查与红线排查报告】\n",
            "> **审查维度**: 合同效力性审查 · 违约责任平衡性 · 管辖权审查 · 4倍LPR及违约金法定红线\n",
            "### 📋 一、合同基本要素与效力健全度诊断",
        ]

        # 1. 检查借款高利与违约金
        has_usury = bool(re.search(r"(\d+(?:\.\d+)?)%", contract_text))
        has_jurisdiction = any(k in contract_text for k in ["管辖", "法院", "仲裁"])
        has_unilateral = any(k in contract_text for k in ["单方解除", "随时解除", "不得退还", "一概不退"])
        has_delivery_term = any(k in contract_text for k in ["交付", "交货", "送达", "验收", "借款发放"])

        if has_delivery_term:
            lines.append("- ✅ **履行与交付机制**: 合同具备基本履行与交付要件表述，建议细化验收确认书与书面留痕签字凭证。")
        else:
            lines.append("- ⚠️ **交付与验收标准缺失**: 合同对交付完成的时间节点、验收合格异议期（民法典第620条）缺乏明确约定，存在验收争议风险。")

        lines.append("\n### 🚨 二、重点条款法律风险排查与红线修订建议 (Redline)")

        # 风险项 1: 利息与违约金过高
        if has_usury:
            lines.append(
                "#### 1. 利率与违约金条款审查 (🚨 高危风险)\n"
                "- **原条款风险分析**: 合同中约定的利率或违约金比例偏高。依据《最高人民法院关于审理民间借贷案件适用法律若干问题的规定》第二十五条及民法典第五百八十五条，约定的利息总和超过合同成立时一年期LPR四倍的，超出部分人民法院一律不予保护；约定的违约金超过守约方实际损失30%的，法院将依法予以酌减。\n"
                "- **修订红线方案 (推荐直接替换为)**:\n"
                "  > “借款利息及逾期付款违约金合计按照全国银行间同业拆借中心公布的一年期贷款市场报价利率（LPR）的四倍计算；如发生逾期，借款人自愿承担出借人为主张债权所支出的合理诉讼费、保全费及律师费。”\n"
            )
        else:
            lines.append(
                "#### 1. 违约责任条款审查 (💡 完善建议)\n"
                "- **原条款分析**: 合同未明确约定逾期履行的具体违约金计算标准及起止日期。\n"
                "- **修订红线方案**:\n"
                "  > “任何一方违约的，违约方应按违约标的金额每日万分之三向守约方支付逾期违约金，并赔偿守约方由此遭受的全部实际损失。”\n"
            )

        # 风险项 2: 管辖权条款
        if has_jurisdiction:
            lines.append(
                "#### 2. 争议解决与管辖法院条款 (⚠️ 中危审查)\n"
                "- **原条款分析**: 合同中包含了管辖法院约定。依据《民事诉讼法》第三十五条，协议管辖必须在“原告住所地、被告住所地、合同签订地、合同履行地、标的物所在地”五地之内选择，且不得违反专属管辖与级别管辖规定。\n"
                "- **修订红线方案**:\n"
                "  > “因履行本协议发生的一切争议，双方应友好协商；协商不成的，由出借人/供货方/守约方住所地人民法院诉讼管辖。”\n"
            )
        else:
            lines.append(
                "#### 2. 管辖权条款缺失 (🚨 严重漏洞)\n"
                "- **原条款分析**: 合同完全未约定争议解决条款！一旦发生违约，守约方可能不得不奔波至被告户籍所在地法院起诉，大幅推高维权时间与差旅成本。\n"
                "- **修订红线方案**:\n"
                "  > “因本合同引起的或与本合同有关的任何争议，均由守约方所在地有管辖权的人民法院管辖。”\n"
            )

        # 风险项 3: 单方霸王条款审查
        if has_unilateral:
            lines.append(
                "#### 3. 单方免责或押金一概不退条款 (🚨 效力存疑)\n"
                "- **原条款分析**: 合同中出现类似“单方解除”、“押金概不退还”之约定。依民法典第四百九十七条，格式条款提供方不合理地免除或者减轻其责任、加重对方责任、限制对方主要权利的，该格式条款自始无效。\n"
                "- **修订红线方案**:\n"
                "  > “合同解除时，双方应于解除之日起3日内完成资产设施清点与交接结算。非违约方实际遭受的合理空置或直接损失，经核算后由押金多退少补结清。”\n"
            )

        lines.append(
            "\n### 🛡️ 三、签约与履约留痕实操指南\n"
            "1. **身份信息核验**: 签署人必须附身份证正反面复印件（个人）或加盖鲜章并由法定代表人签字（企业）；\n"
            "2. **骑缝章与捺印**: 多页合同必须加盖骑缝章或每页由当事人亲笔签名捺印，防范抽页替换；\n"
            "3. **送达地址确认条款**: 必须在合同尾部明确约定各方接收诉讼文书与法律通知的法定电子邮箱、微信号与快递物理地址，约定“一旦寄出即视为有效送达”。"
        )
        return "\n".join(lines)

    async def areview(self, contract_text: str) -> Tuple[str, Dict[str, Any]]:
        user_prompt = f"请审查以下合同文本或条款草案：\n\n```text\n{contract_text}\n```"
        text, usage = await ainvoke_legal_text(_CONTRACT_REVIEW_SYSTEM_PROMPT, user_prompt, timeout=5.0)
        if not text:
            return self.review_fallback(contract_text), usage
        return text, usage


contract_reviewer = ContractReviewer()
