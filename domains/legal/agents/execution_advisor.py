    async def aadvise(self, prompt: str) -> Tuple[str, Dict[str, Any]]:
        text, usage = await ainvoke_legal_text(
            system_prompt=_EXECUTION_SYSTEM_PROMPT,
            user_prompt=prompt,
        )
        if text and len(text.strip()) > 50:
            return text, usage
        return self.advise_fallback(prompt), usage


