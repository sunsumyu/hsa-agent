    async def adraft(self, prompt: str) -> Tuple[str, Dict[str, Any]]:
        user_prompt = f"请起草以下合同或法律文书：\n\n```text\n{prompt}\n```"
        text, usage = await ainvoke_legal_text(_CONTRACT_DRAFT_SYSTEM_PROMPT, user_prompt, timeout=6.0)
        if not text:
            return self.draft_fallback(prompt), usage
        return text, usage


