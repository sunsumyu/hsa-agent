    def draft_fallback(self, prompt: str) -> str:
        prompt_lower = prompt.lower()
        if any(kw in prompt for kw in ["借款", "借条", "借据", "欠条", "民间借贷"]):
            return self._draft_loan_agreement(prompt)
        elif any(kw in prompt for kw in ["租房", "租赁", "房租", "商铺", "写字楼"]):
            return self._draft_lease_agreement(prompt)
        elif any(kw in prompt for kw in ["劳动", "雇佣", "员工", "入职", "离职", "聘用"]):
            return self._draft_labor_agreement(prompt)
        elif any(kw in prompt for kw in ["律师函", "催收", "催款", "催告", "告知函"]):
            return self._draft_demand_letter(prompt)
        else:
            return self._draft_sales_agreement(prompt)

